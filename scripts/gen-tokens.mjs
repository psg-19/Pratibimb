// Generates the palette CSS custom properties and the typed palette list from design/tokens.json.
// Run with `npm run tokens` (also runs before dev/build). Output files are committed so the app
// builds without this step, but they should never be edited by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));

const HUES = ['g', 'pk', 'b', 'o', 'r', 'y'];
// Single-accent palettes have no hue tokens: every hue maps to the accent family.
const HUE_FALLBACK = { bg: 'accent-wash', mid: 'accent-mid', dot: 'accent', ink: 'accent-deep' };

const banner = '/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */\n';

const fallback = HUES.flatMap((h) =>
  Object.entries(HUE_FALLBACK).map(([step, to]) => `--${h}-${step}:var(--${to})`),
).join(';');

// WCAG relative-luminance contrast between two #RRGGBB colours.
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
};
const contrast = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const AA = 4.5;

/**
 * Accessibility fallbacks, derived per palette. Components read them as
 * var(--on-mid-ink, var(--h-ink)) etc., so palettes that already pass keep the design colours.
 *  --on-mid-ink / --on-mid-muted: text on a selected (-mid) hue surface.
 *  --risk-on-tint: small risk-coloured text on washes and tints.
 */
function a11yFallbacks(t) {
  const hues = 'g-bg' in t ? HUES : [null];
  const pair = (h, step) => (h ? t[`${h}-${step}`] : t[`accent-${step === 'ink' ? 'deep' : step}`]);
  const out = {};
  if (hues.some((h) => contrast(pair(h, 'ink'), pair(h, 'mid')) < AA)) out['on-mid-ink'] = 'var(--ink)';
  if (hues.some((h) => contrast(t.muted, pair(h, 'mid')) < AA)) out['on-mid-muted'] = 'var(--soft-ink)';
  // Surfaces where small risk-coloured text appears: alert cards (risk wash) and the yellow
  // "what the twin has learned" card (accent wash in single-accent palettes).
  const tints = [t['risk-wash'], 'y-bg' in t ? t['y-bg'] : t['accent-wash']];
  if (tints.some((bg) => contrast(t.risk, bg) < AA)) out['risk-on-tint'] = 'var(--risk-deep)';
  return out;
}

let css = banner + `[data-palette]{${fallback}}\n`;
for (const [id, palette] of Object.entries(tokens.palettes)) {
  const selector = id === tokens.default ? `:root,[data-palette="${id}"]` : `[data-palette="${id}"]`;
  const all = { ...palette.tokens, ...a11yFallbacks(palette.tokens) };
  const body = Object.entries(all)
    .map(([k, v]) => `--${k}:${v}`)
    .join(';');
  css += `${selector}{${body}}\n`;
  const fixes = Object.keys(a11yFallbacks(palette.tokens));
  if (fixes.length) console.log(`  ${id}: contrast fallbacks ${fixes.join(', ')}`);
}
writeFileSync(resolve(root, 'src/styles/tokens.css'), css);

const list = Object.entries(tokens.palettes).map(([id, p]) => ({
  id,
  name: p.name,
  mixed: 'g-bg' in p.tokens,
  swatch:
    'g-bg' in p.tokens
      ? [p.tokens.accent, p.tokens['g-mid'], p.tokens['pk-mid'], p.tokens['y-mid']]
      : [p.tokens.accent, p.tokens['accent-mid'], p.tokens['risk-line']],
}));
const ts =
  banner.replace('/*', '//').replace(' */', '') +
  `export const PALETTES = ${JSON.stringify(list, null, 2)} as const;\n\n` +
  `export type PaletteId = (typeof PALETTES)[number]['id'];\n\n` +
  `export const DEFAULT_PALETTE: PaletteId = ${JSON.stringify(tokens.default)};\n`;
writeFileSync(resolve(root, 'src/theme/palettes.gen.ts'), ts);

console.log(`tokens: ${list.length} palettes → src/styles/tokens.css, src/theme/palettes.gen.ts`);
