import { describe, expect, it } from 'vitest';
import { parseCgmCsv, parseTimestamp } from '../shared/importers/cgmCsv';
import { istTime } from '../shared/time';
import { parseMealOffline, draftOffline } from '../server/ai/offline';
import { parseMeds } from '../shared/synth/template';

describe('CGM CSV import', () => {
  it('reads a Dexcom Clarity export (EGV rows only)', () => {
    const csv = [
      'Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams)',
      '1,,FirstName,,Asha,,,,,',
      '2,2026-10-01T08:00:00,EGV,,,,iPhone,120,,',
      '3,2026-10-01T08:05:00,EGV,,,,iPhone,126,,',
      '4,2026-10-01T08:07:00,Carbs,,,,iPhone,,,45',
      '5,2026-10-01T08:10:00,EGV,,,,iPhone,Low,,',
    ].join('\n');
    const r = parseCgmCsv(csv);
    expect(r.format).toBe('dexcom');
    expect(r.readings).toEqual([
      { t: istTime(2026, 10, 1, 8, 0), mgdl: 120 },
      { t: istTime(2026, 10, 1, 8, 5), mgdl: 126 },
      { t: istTime(2026, 10, 1, 8, 10), mgdl: 40 },
    ]);
  });

  it('reads a LibreView export with a metadata first line and day-first dates', () => {
    const csv = [
      'Glucose Data,Generated on,13-10-2026 10:00 UTC,Generated by,Asha',
      'Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin',
      'FreeStyle LibreLink,ABC,02-10-2026 21:15,0,142,,',
      'FreeStyle LibreLink,ABC,02-10-2026 21:20,1,,150,',
      'FreeStyle LibreLink,ABC,02-10-2026 21:22,6,,,',
    ].join('\n');
    const r = parseCgmCsv(csv);
    expect(r.format).toBe('libreview');
    expect(r.readings.map((x) => x.mgdl)).toEqual([142, 150]);
    expect(r.readings[0].t).toBe(istTime(2026, 10, 2, 21, 15));
  });

  it('converts mmol/L and snaps to the 5-minute grid', () => {
    const r = parseCgmCsv('time,glucose (mmol/L)\n2026-10-03 07:02,5.5\n2026-10-03 07:07,10.0\n');
    expect(r.readings).toEqual([
      { t: istTime(2026, 10, 3, 7, 0), mgdl: 99 },
      { t: istTime(2026, 10, 3, 7, 5), mgdl: 180 },
    ]);
  });

  it('rejects files without glucose columns', () => {
    expect(() => parseCgmCsv('name,age\nAsha,50')).toThrow(/timestamp and glucose/);
  });

  it('parses 12-hour timestamps', () => {
    expect(parseTimestamp('13/10/2026 09:40 PM')).toBe(istTime(2026, 10, 13, 21, 40));
  });
});

describe('offline AI fallbacks', () => {
  it('estimates carbs from a description, including Kannada and Hindi words', () => {
    expect(parseMealOffline('two chapati, dal and a cup of curd').totalCarbs).toBe(60);
    const kn = parseMealOffline('ಎರಡು ಚಪಾತಿ ಮತ್ತು ಸಾರು');
    expect(kn.items.map((i) => i.name)).toEqual(['Chapati', 'Rasam']);
    expect(kn.totalCarbs).toBe(35);
    expect(parseMealOffline('दो रोटी और दाल').totalCarbs).toBe(50);
  });

  it('flags what it could not recognise', () => {
    const r = parseMealOffline('chapati and a mystery dish');
    expect(r.confidence).toBe('low');
    expect(r.notes).toMatch(/mystery dish/);
  });

  it('drafts messages in each language without dose advice', () => {
    for (const lang of ['en', 'hi', 'kn'] as const) {
      const d = draftOffline('snack', 'Suresh', lang);
      expect(d.message).toContain('Suresh');
      expect(d.english).toMatch(/snack before bed/);
    }
  });

  it('reads medicine schedules from free text', () => {
    expect(parseMeds('Metformin 1 g twice daily')).toEqual([{ drug: 'metformin', dose: 1000, times: ['morning', 'evening'] }]);
    expect(parseMeds('metformin 500 mg OD, glimepiride 2 mg').map((m) => [m.drug, m.dose])).toEqual([
      ['metformin', 500],
      ['glimepiride', 2],
    ]);
  });
});
